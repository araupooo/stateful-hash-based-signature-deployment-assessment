#!/usr/bin/env python3
"""Render docs/index.html from a run's results.json + findings.md/claims.md.

The page is self-contained (inline CSS, no external resources) and is
regenerated by run_all.sh from outputs/run1/results.json. It is excluded
from SHA256SUMS (see README.md) because it is a generated rendering of
the run outputs.
"""
import argparse
import html
import json
import os

PACK = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LMS_SETS = ["LMS_SHA256_H5_W1", "LMS_SHA256_H5_W4", "LMS_SHA256_H10_W1",
            "LMS_SHA256_H10_W4", "LMS_SHA256_H10_W8", "LMS_SHA256_H15_W4",
            "LMS_SHA256_H20_W4"]
XMSS_ALGS = [
    "XMSS-SHA2_10_256", "XMSS-SHA2_16_256", "XMSS-SHA2_20_256",
    "XMSS-SHAKE_10_256", "XMSS-SHAKE_16_256", "XMSS-SHAKE_20_256",
]
SLH_ALGS = [
    "SLH-DSA-SHA2-128s", "SLH-DSA-SHA2-128f",
    "SLH-DSA-SHA2-192s", "SLH-DSA-SHA2-192f",
    "SLH-DSA-SHA2-256s", "SLH-DSA-SHA2-256f",
    "SLH-DSA-SHAKE-128s", "SLH-DSA-SHAKE-128f",
    "SLH-DSA-SHAKE-192s", "SLH-DSA-SHAKE-192f",
    "SLH-DSA-SHAKE-256s", "SLH-DSA-SHAKE-256f",
]


def table(headers, rows):
    th = "".join(f"<th>{html.escape(str(h))}</th>" for h in headers)
    tr = "".join("<tr>" + "".join(f"<td>{html.escape(str(c))}</td>" for c in r) + "</tr>"
                 for r in rows)
    return f"<table><thead><tr>{th}</tr></thead><tbody>{tr}</tbody></table>"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    with open(a.results) as f:
        r = json.load(f)
    with open(os.path.join(PACK, "findings.md")) as f:
        findings = f.read()
    with open(os.path.join(PACK, "claims.md")) as f:
        claims = f.read()

    def sig_rows(algs, impl2):
        rows = []
        for alg in algs:
            if alg not in r["throughput"]:
                rows.append([alg, "not measured (keygen exceeds 240 s)", "", "", ""])
                continue
            t = r["throughput"][alg]
            m = r["memory_kb"][alg]
            # slh-dsa timings use short keys (keygen/sign/verify);
            # liboqs and the C references use *_ms_median keys.
            if impl2 == "slh-dsa":
                k2, s2, v2 = (f"{t[impl2]['keygen']:.4f}",
                             f"{t[impl2]['sign']:.4f}",
                             f"{t[impl2]['verify']:.4f}")
            else:
                k2, s2, v2 = (f"{t[impl2]['keygen_ms_median']:.4f}",
                             f"{t[impl2]['sign_ms_median']:.4f}",
                             f"{t[impl2]['verify_ms_median']:.4f}")
            rows.append([alg,
                         f"{t['liboqs']['keygen_ms_median']:.4f} / {k2}",
                         f"{t['liboqs']['sign_ms_median']:.4f} / {s2}",
                         f"{t['liboqs']['verify_ms_median']:.4f} / {v2}",
                         f"{m['liboqs']} / {m[impl2]}"])
        return rows

    size_rows = []
    for alg in LMS_SETS + XMSS_ALGS + SLH_ALGS:
        v = r["sizes_verified"][alg]
        size_rows.append([alg, str(v["expected"]), str(v["liboqs"]), str(v["match"])])

    state_rows = []
    for alg in LMS_SETS + XMSS_ALGS + SLH_ALGS:
        v = r["state"][alg]
        if v.get("stateless"):
            state_rows.append([alg, f"{v['liboqs_secret_key_bytes']} (stateless)",
                               "unlimited (2^64)", ""])
        elif v.get("liboqs_serialized_secret_key_bytes") is None:
            state_rows.append([alg, "not measured (keygen exceeds 240 s)",
                               f"expected {v['expected_total']}", ""])
        else:
            ref_key = ("hash-sigs_secret_key_bytes" if "hash-sigs_secret_key_bytes" in v
                       else "xmss-reference_secret_key_bytes")
            state_rows.append([alg,
                               f"{v['liboqs_serialized_secret_key_bytes']} (liboqs) / "
                               f"{v[ref_key]} (reference)",
                               str(v["sigs_total"]),
                               str(v["sigs_remaining_after_keygen"])])

    art_rows = []
    for alg in LMS_SETS + XMSS_ALGS + SLH_ALGS:
        e = r["artifact_size_impact"][alg]
        art_rows.append([alg, str(e["signature_bytes"]), str(e["vs_ed25519_64B"]),
                         f"{e['overhead_pct_manifest_1KiB']}%",
                         f"{e['overhead_pct_wheel_100KiB']}%",
                         f"{e['overhead_pct_tarball_5MiB']}%",
                         f"{e['overhead_pct_binary_50MiB']}%"])

    adv_rows = []
    for alg in sorted(r["adversarial"]):
        for k, v in sorted(r["adversarial"][alg].items()):
            adv_rows.append([alg, k, str(v)])
    x_rows = []
    for alg in sorted(r["cross_implementation"]):
        for k, v in sorted(r["cross_implementation"][alg].items()):
            x_rows.append([alg, k, str(v)])
    det_rows = []
    for alg in sorted(r["determinism"]):
        for k, v in sorted(r["determinism"][alg].items()):
            det_rows.append([alg, k, str(v)])
    env = r["environment"]
    exh = r["exhaustion"]

    body = f"""<!DOCTYPE html>
<html lang="en"><head><meta charset="utf-8">
<title>Stateful Hash-Based Signature Deployment Assessment — Findings</title>
<style>
body{{font-family:system-ui,sans-serif;max-width:1000px;margin:2em auto;padding:0 1em;line-height:1.5;color:#111}}
table{{border-collapse:collapse;margin:1em 0;width:100%;font-size:.92em}}
th,td{{border:1px solid #999;padding:.35em .6em;text-align:left;vertical-align:top}}
th{{background:#eee}}
pre{{white-space:pre-wrap;background:#f6f6f6;padding:1em;overflow-x:auto}}
code{{background:#f0f0f0;padding:0 .2em}}
h1{{font-size:1.6em}} h2{{border-top:2px solid #333;padding-top:.6em}}
</style></head><body>
<h1>Stateful Hash-Based Signature Deployment Assessment</h1>
<p>Repository: <a href="https://github.com/araupooo/stateful-hash-based-signature-deployment-assessment">https://github.com/araupooo/stateful-hash-based-signature-deployment-assessment</a><br>
Rendered findings page (this page): <a href="https://araupooo.github.io/stateful-hash-based-signature-deployment-assessment/">https://araupooo.github.io/stateful-hash-based-signature-deployment-assessment/</a></p>
<p>Reproducible LMS / XMSS / SLH-DSA assessment: benchmarks across
pinned liboqs 0.16.0 (C), the hash-sigs LMS reference (C), the
xmss-reference XMSS reference (C) and slh-dsa 0.2.5 (pure Python),
adversarial-input behaviour, state-exhaustion behaviour, one
reproduced state-management failure mode and a tested remediation.
All numbers below are the medians from <code>outputs/run1/</code>;
timing values vary between runs by design (see README.md, comparison
rule). slh-dsa throughput is n=1 and indicative only — the pure-Python
signer takes seconds per signature. Rust and Go were not benchmarked:
this machine has no cargo/rustc or Go toolchain. H20 parameter sets
are sizes-only: keygen for a 2<sup>20</sup>-leaf tree exceeds 240 s on
this machine, so no keygen-dependent measurement was attempted for
them.</p>

<h2>Throughput — LMS (median ms per operation, liboqs / hash-sigs)</h2>
{table(["Parameter set", "Keygen", "Sign", "Verify", "Peak RSS KB (liboqs / hash-sigs)"], sig_rows(LMS_SETS, "hash-sigs"))}

<h2>Throughput — XMSS (median ms per operation, liboqs / xmss-reference)</h2>
{table(["Parameter set", "Keygen", "Sign", "Verify", "Peak RSS KB (liboqs / xmss-reference)"], sig_rows(XMSS_ALGS, "xmss-reference"))}

<h2>Throughput — SLH-DSA (median ms per operation, liboqs / slh-dsa, n=1 for slh-dsa)</h2>
{table(["Parameter set", "Keygen", "Sign", "Verify", "Peak RSS KB (liboqs / slh-dsa)"], sig_rows(SLH_ALGS, "slh-dsa"))}

<h2>Key and signature sizes (RFC 8554 / RFC 8391 formulas, FIPS 205 Table 2)</h2>
{table(["Parameter set", "Expected", "liboqs {pk, sk, sig} bytes", "Match"], size_rows)}

<h2>State (serialized secret-key size and signature budget)</h2>
{table(["Parameter set", "Serialized secret-key bytes", "Signatures total", "Remaining after keygen"], state_rows)}

<h2>State exhaustion</h2>
<pre>Algorithm: {html.escape(str(exh["algorithm"]))}
Signatures total (reported): {exh["sigs_total"]}
Signing all {exh["sigs_total"]} signatures in sequence: ok={exh["sign_all_total_ok"]}
One signature past the reported total: rc={exh["sign_after_exhaustion_rc"]}, produced={exh["sign_after_exhaustion_produced_signature"]}, verifies={exh["sign_after_exhaustion_verifies"]}
One more signature after that: rc={exh["third_sign_after_exhaustion_rc"]}, output={html.escape(str(exh["third_sign_after_exhaustion_output"]))}
XMSS-SHA2_10_256 total (reported): {exh["xmss_total"]}
XMSS signing all {exh["xmss_total"]} in sequence: ok={exh["xmss_sign_all_total_ok"]}
XMSS one signature past the reported total: rc={exh["xmss_sign_after_exhaustion_rc"]}, produced={exh["xmss_sign_after_exhaustion_produced_signature"]}, verifies={exh["xmss_sign_after_exhaustion_verifies"]}</pre>

<h2>Artifact-size impact (signature bytes vs release artifact)</h2>
{table(["Parameter set", "Signature bytes", "vs Ed25519 (64 B)", "1 KiB manifest", "100 KiB wheel", "5 MiB tarball", "50 MiB binary"], art_rows)}

<h2>Adversarial-input behaviour</h2>
{table(["Parameter set", "Case", "Outcome"], adv_rows)}

<h2>Cross-implementation agreement</h2>
{table(["Parameter set", "Check", "Result"], x_rows)}

<h2>Signing determinism (same state, same message)</h2>
{table(["Parameter set", "Check", "Result"], det_rows)}

<h2>Environment (this machine)</h2>
<pre>OpenSSL version: {html.escape(env["openssl_version"])}
OpenSSL lists ML-DSA: {env["openssl_lists_ml_dsa"]}
OpenSSL lists SLH-DSA: {env["openssl_lists_slh_dsa"]}
OpenSSL lists LMS: {env["openssl_lists_lms"]}
OpenSSL lists XMSS: {env["openssl_lists_xmss"]}
Python: {html.escape(env["python"])}
liboqs stateful keygen/sign supported: {env["liboqs_stfl_keygen_and_sign_supported"]}</pre>

<h2>Findings</h2>
<pre>{html.escape(findings)}</pre>

<h2>Claim-to-evidence index</h2>
<pre>{html.escape(claims)}</pre>

<h2>Reproduce</h2>
<pre>bash scripts/run_all.sh            # full rebuild + benchmark into outputs/run1/
bash scripts/clean_reproduce.sh    # fresh-copy re-run into outputs/run2-clean/ + comparison
bash scripts/verify_digests.sh     # SHA-256 check over all shippable files</pre>
<p>Sources: RFC 8391 and RFC 8554 (bundled as src/RFC.8391.txt and
src/RFC.8554.txt), NIST SP 800-208 (bundled as src/SP.800-208.pdf),
FIPS 203/204/205 (bundled as src/FIPS.20x.pdf); liboqs 0.16.0;
hash-sigs; xmss-reference; slh-dsa 0.2.5. Full citations in
citations.md.</p>
</body></html>
"""
    with open(a.out, "w") as f:
        f.write(body)
    print(f"wrote {a.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
